"""Subject Pydantic schemas.

Satisfies Requirements:
  - 7.1: Subject metadata — bound to a published study version.
  - 7.2: Subject number unique within the study (validated at service layer);
          generated by the configured rule when not explicitly provided.
  - 7.3: Subject status transitions (enforced at service layer).
  - 7.5: Subject casebook structure with clinical status.
  - 22.2: Soft-delete retains the record.
  - 21.2: List endpoints return pagination envelope.
"""

from __future__ import annotations

from uuid import UUID

from pydantic import Field

from app.models.edc.subject import SubjectStatus
from app.schemas.shared.base import BaseCreateSchema, BaseSchema, UtcDatetime

# ---------------------------------------------------------------------------
# Subject schemas (Requirement 7)
# ---------------------------------------------------------------------------


class SubjectCreate(BaseCreateSchema):
    """Request body for creating a new Subject (Requirement 7.1, 7.2).

    The site under which the subject is enrolled is supplied separately
    (path/route or explicit argument). ``subject_number`` is optional: when
    omitted, the Subject_Service generates the identifier by the configured
    rule. When provided, it is used as-is (and still enforced unique within
    the study).
    """

    site_id: UUID
    subject_number: str | None = Field(
        None,
        min_length=1,
        max_length=100,
        description="Optional; generated by the configured rule when omitted",
    )


class SubjectUpdate(BaseCreateSchema):
    """Request body for updating a Subject's metadata (partial PATCH).

    Only the subject number is editable post-creation; status changes flow
    through the dedicated transition endpoints (Requirement 7.3).
    """

    subject_number: str | None = Field(
        None, min_length=1, max_length=100, description="Updated subject identifier"
    )


class SubjectStatusTransition(BaseCreateSchema):
    """Request body for transitioning a Subject's status (Requirement 7.3)."""

    target_status: SubjectStatus


class SubjectDelete(BaseCreateSchema):
    """Request body for soft-deleting a Subject (Requirement 22.2)."""

    reason: str = Field(..., min_length=1, description="Reason for deletion")


class SubjectResponse(BaseSchema):
    """Response schema for a Subject record (Requirement 7.1)."""

    id: UUID
    study_id: UUID
    site_id: UUID
    study_version_id: UUID
    current_phase_definition_id: UUID | None = None
    arm_definition_id: UUID | None = None
    subject_number: str
    status: SubjectStatus
    created_by: UUID
    created_at: UtcDatetime
    updated_at: UtcDatetime | None = None
    deleted_at: UtcDatetime | None = None
    deleted_by: UUID | None = None
    deletion_reason: str | None = None


class SubjectListResponse(SubjectResponse):
    """Subject row enriched with human-readable site and phase details."""

    site_name: str | None = None
    current_phase_name: str | None = None
    current_phase_type: str | None = None


# ---------------------------------------------------------------------------
# Casebook schemas (Requirement 7.5)
# ---------------------------------------------------------------------------


class CasebookFormEntry(BaseSchema):
    """A form entry within a casebook visit."""

    form_instance_id: UUID | None = None
    form_definition_id: UUID | None = None
    name: str | None = None
    status: str


class CasebookVisitEntry(BaseSchema):
    """A visit entry within a casebook."""

    visit_instance_id: UUID | None = None
    visit_definition_id: UUID | None = None
    name: str | None = None
    status: str
    forms: list[CasebookFormEntry] = Field(default_factory=list)


class CasebookResponse(BaseSchema):
    """Response schema for a subject casebook (Requirement 7.5)."""

    subject_id: UUID
    subject_number: str
    status: SubjectStatus
    study_version_id: UUID
    current_phase_definition_id: UUID | None = None
    current_phase_name: str | None = None
    current_phase_type: str | None = None
    arm_definition_id: UUID | None = None
    arm_name: str | None = None
    visits: list[CasebookVisitEntry] = Field(default_factory=list)


class SubjectPhaseOption(BaseSchema):
    """One configured phase available for the subject's published design."""

    id: UUID
    name: str
    phase_type: str
    display_order: int
    visit_definition_ids: list[UUID] = Field(default_factory=list)


class SubjectArmOption(BaseSchema):
    """One configured arm available for assignment."""

    id: UUID
    name: str
    display_order: int
    description: str | None = None


class SubjectPhaseStateResponse(BaseSchema):
    """Current phase/arm state plus choices from the published design."""

    current_phase_definition_id: UUID | None = None
    current_phase_name: str | None = None
    current_phase_type: str | None = None
    arm_definition_id: UUID | None = None
    arm_name: str | None = None
    phases: list[SubjectPhaseOption] = Field(default_factory=list)
    next_phases: list[SubjectPhaseOption] = Field(default_factory=list)
    arms: list[SubjectArmOption] = Field(default_factory=list)


class SubjectPhaseUpdate(BaseCreateSchema):
    """Move a subject to a configured phase, selecting an arm when required."""

    phase_definition_id: UUID
    arm_definition_id: UUID | None = None
